// Narrow language corrections, never new facts, legal reasoning or a new procedure.
export function normalizeAgreement(text){
 return String(text).replace(/следва да бъде изключено необходимостта/gu,'следва да бъде изключена необходимостта');
}
export function administrativeStyle(text){
 let out=normalizeAgreement(text);
 out=out.replace(/следва да се издаде писмо с констатация, че/gu,'Ви уведомявам, че')
  .replace(/Следва да се издаде писмо с констатация, че/gu,'Ви уведомявам, че')
  .replace(/конкретно посочвам, че/gu,'Ви уведомявам, че')
  .replace(/Конкретно посочвам, че/gu,'Ви уведомявам, че');
 out=out.replace(/(?<![\p{L}\p{N}])(на|за|от|по|че|при|без)\s+\1(?![\p{L}\p{N}])/giu,'$1');
 return out;
}
export function editorialWarnings(text){
 const notes=[];
 if(/подлежи на разглеждане и издаване на административен акт/iu.test(text))notes.push('Остава формулировка за бъдещо разглеждане и издаване на акт. Експертът трябва да уточни дали текстът е уведомяване или указание за следващо действие; редакторът не избира вместо него.');
 if(/подлежи на последващо експертно потвърждение/iu.test(text))notes.push('В текста остава служебна формулировка за последващо експертно потвърждение. Преценете дали принадлежи в документа към адресата.');
 if(/следва да бъде изключена необходимостта/iu.test(text))notes.push('Съгласуването „изключена необходимостта“ е езиково коригирано. Самата процедурна формулировка остава за експертен преглед.');
 return notes;
}
