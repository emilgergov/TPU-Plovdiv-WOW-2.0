'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const source=fs.readFileSync(path.resolve(__dirname,'../../vt03/kt80/integration/kt83-vt01-automatic-route-p1.js'),'utf8');
const ctx={module:{exports:{}},window:{}};
vm.runInNewContext(source,ctx);
const api=ctx.module.exports;
const C={caseId:'CASE_123',generation:1,evidenceRevision:7};
let current={...C};
const route=api.coordinator({current:()=>current});
const ev={...C,verified:true,pdf1Verified:true,geometryVerified:true};
let count=0;
const verify=(label,fn)=>{fn();count++;console.log('PASS '+label)};
verify('initial route inactive',()=>assert.equal(route.snapshot().valid,false));
verify('no start without separate subject and scope',()=>assert.equal(route.start({subject:true}).ok,false));
verify('start after expert confirmations',()=>assert.equal(route.start({subject:true,scope:true}).ok,true));
verify('prevent jumping to normative',()=>assert.equal(route.advance('normative_v11',ev).ok,false));
verify('reject GIS phase with no PDF1 receipt',()=>assert.equal(route.advance('evidence',{...C,verified:true}).ok,false));
verify('GIS verified receipt advances',()=>assert.equal(route.advance('evidence',ev).ok,true));
verify('evidence advances to normative',()=>assert.equal(route.advance('normative_v11',ev).ok,true));
verify('require reasoned legal assessment',()=>assert.equal(route.advance('motivated_proposal',ev).ok,false));
verify('accept reasoned legal assessment',()=>assert.equal(route.advance('motivated_proposal',{...ev,reasonedAssessment:'Мотивирана оценка'}).ok,true));
verify('require motivated proposal for draft',()=>assert.equal(route.advance('out_draft',ev).ok,false));
verify('permit draft with motivated proposal',()=>assert.equal(route.advance('out_draft',{...ev,motivatedProposal:'Предложение'}).ok,true));
verify('reject draft for another case',()=>assert.equal(route.complete({...ev,caseId:'OTHER'}).ok,false));
verify('complete draft only as unsigned review project',()=>{assert.equal(route.complete(ev).ok,true);assert.match(route.snapshot().reason,/Неподписан проект/)});
verify('case generation change invalidates',()=>{current={...C,generation:2};assert.equal(route.snapshot().valid,false)});
verify('invalidated route refuses further completion',()=>assert.equal(route.complete(ev).ok,false));
console.log('KT134: E1-E5 route guard '+count+'/'+count);
