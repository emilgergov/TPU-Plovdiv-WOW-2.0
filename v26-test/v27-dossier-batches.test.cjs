const assert=require('node:assert/strict');
const fs=require('node:fs');const vm=require('node:vm');const ctx={};
vm.runInNewContext(fs.readFileSync(__dirname+'/v27-dossier-batches.js','utf8'),ctx);
const api=ctx.V27DossierBatches;
const source={files:[{path:'a.txt',text:'A'.repeat(12003)},{path:'b.pdf',error:'No text'},{path:'c.txt',text:'C'.repeat(2000)}]};
const p=api.prepare(source,{chunkChars:5000});
assert.equal(p.batches.length,4);
assert.equal(p.complete,false);
assert.equal(p.omittedCount,1);
assert.equal(p.manifest[1].status,'unreadable');
const restored=p.batches.filter(x=>x.file==='a.txt').map(x=>x.text).join('');
assert.equal(restored,'A'.repeat(12003));
const req=api.toRequests(p,{maxRequestChars:12000});
assert.ok(req.requests.length>=2);
assert.equal(req.requests.flat().length,p.batches.length);
const limited=api.prepare({files:[{path:'big',text:'A'.repeat(1500)},{path:'other',text:'B'.repeat(1500)}]},{chunkChars:1000,maxTotalChars:2000});
assert.equal(limited.manifest[1].status,'over_budget');
assert.equal(limited.complete,false);
assert.throws(()=>api.prepare(source,{chunkChars:100}),/Invalid chunkChars/);
console.log('V27.1 P3 dossier batching: PASS');
