#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path');
const rd=x=>fs.readFileSync(path.join(__dirname,x),'utf8');
const baseline=rd('V27_27_KT77_04_4_R4_CONTEXT_ADMIN_PAGINATION.html');
const candidate=rd('V27_27_KT77_04_5_PDF2_LEGAL_REQUISITES_PREVIEW.html');
const reverted=candidate.replace('<script src="v27-preview/kt77-04-5-legislation-provenance.js?v=kt77-045-v1"></script>\n','').replace('v27-preview/kt77-04-5-pdf2-verified-metadata-preview.js?v=kt77-045-v1','v27-preview/kt77-04-4b-pdf1-generator-auto-context-preview.js?v=kt77-044b-r2-names').replace('v27-preview/kt77-04-5-pdf2-strong-legal-renderer.js?v=kt77-045-v1','v27-preview/kt77-04-4d-offline-pdf-pagekeep.js?v=kt77-044d-1');
