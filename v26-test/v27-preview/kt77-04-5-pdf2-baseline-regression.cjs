#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),crypto=require('node:crypto'),vm=require('node:vm');
const root=__dirname,read=p=>fs.readFileSync(path.resolve(root,p),'utf8');
const hash=s=>crypto.createHash('sha1').update('blob '+Buffer.byteLength(s)+'\0'+s).digest('hex');
const acceptedHtml=read('V27_27_KT77_04_4_R4_CONTEXT_ADMIN_PAGINATION.html');
const acceptedGenerator=read('kt77-04-4b-pdf1-generator-auto-context-preview.js');
const prevGenerator=read('kt77-04-2-pdf1-approved-10-edits-preview.js');
const currentPdf1=read('kt77-04-4d-offline-pdf-pagekeep.js');
const sourcePdf1=read('kt77-04-2-offline-pdf-hires.js');
const zzt=read('kt77-r11-zzt-supplement.js');
const legal=read('kt60-3-normative-adapter.js');
const norm=read('v26-normative-register.js');
const annex=read('../v26-annex2-browser.js');
assert.equal(hash(acceptedHtml),'28795bfc40701a78cfeacd9bdfbf063c4e5d8e95','Accepted KT77-04.4 HTML modified');
assert.equal(hash(acceptedGenerator),'a551912a68d01bd9c64fb93db6ed7720ef765370','Accepted PDF1/Word/PDF2 package altered');
assert.equal(hash(currentPdf1),'15e76daebe068cd2900749103bad068f46445471','Accepted 300dpi pagination renderer altered');
assert.equal(hash(sourcePdf1),'24ad16d3f8f4992348494e4d6c65644df865005e','Old PDF1 fallback altered');
for(const x of [acceptedGenerator,currentPdf1,legal,norm,zzt,annex])new vm.Script(x);
const region=s=>s.slice(s.indexOf('function normativePdf('),s.indexOf('async function make('));
assert(region(acceptedGenerator).length>5000,'Missing normative PDF2 generator');
assert.equal(region(acceptedGenerator),region(prevGenerator),'PDF2 generator drifted during PDF1 changes');
assert(acceptedGenerator.includes('if(kind===2)return pdfBlob(normativePdf(results,register));'),'PDF2 independently generated, no context dependence');
assert(acceptedGenerator.includes('function scenarioFromGIS(results,roles)'),'A/B logic must remain present');
assert(!acceptedGenerator.slice(acceptedGenerator.indexOf('function scenarioFromGIS('),acceptedGenerator.indexOf('function docx(')).includes('territories'),'ZT must not redefine A/B');
const pdf2=region(acceptedGenerator);
assert(pdf2.includes('„ТПУ Пловдив — ГИС анализ“'),'Known outdated document reference not yet resolved');
assert(pdf2.includes("const records=register?.records||[]"),'Normative register not attached');
assert(pdf2.includes("source||''"),'Normative source field not present');
assert(pdf2.includes("https:"),'PDF2 source screening changed unexpectedly');
assert(!pdf2.includes('KT77R11ZZT')&&!pdf2.includes('kt77041ZtFindings'),'ZT supplementary facts are not yet included: keep as open finding');
assert(norm.includes("data/normative-archive-register.json")&&norm.includes('normative/sources.json'),'Normative registry sources changed');
assert(norm.includes("verified-legal-excerpts-20261028.json"),'Verified legal excerpts source missing');
assert(zzt.includes('source_verification_required'),'ZT sources need explicit verification status');
assert(legal.includes("catalog_only")&&legal.includes("verified_citation"),'Normative evidence levels need distinction');
assert(annex.includes("standalonePDF(state.gis.results||[],2,"),'PDF2 UI must route to PDF2 generator');
console.log('PASS KT77-04.5 baseline: immutable accepted PDF1, separate PDF2, unaffected Word/scenario, preserved legal register and evidence tiers');
console.log('OPEN ISSUES: outdated PDF1 document name, missing systematic ZT facts, local archive use not established; no unverified law text generated');
