def new_from_original():
    """Keep existing A Word package, headers, footers, styles and image relationships."""
    d=Document(str(TEMPLATE))
    # A's main body contains example-specific text; remove it but retain
    # the original section, header/footer, image parts and possible first logo block.
    paragraphs=list(d.paragraphs)
    media=[]
    for i,p in enumerate(paragraphs):
        if i<7 and (p._element.xpath('.//w:drawing') or p._element.xpath('.//w:pict')):
            media.append(p._element)
    for table in list(d.tables):
        table._element.getparent().remove(table._element)
    for p in paragraphs:
        if p._element.getparent() is not None:
            p._element.getparent().remove(p._element)
    body=d.element.body
    for m in media:
        body.insert(0,m)
    sec=d.sections[0]
    sec.top_margin=Cm(2.1)
    sec.bottom_margin=Cm(1.8)
    sec.left_margin=Cm(2.45)
    sec.right_margin=Cm(2.05)
    normal=d.styles["Normal"]
    normal.font.name="Verdana"
    normal.font.size=Pt(10)
    normal.paragraph_format.space_after=Pt(5)
    normal.paragraph_format.line_spacing=1.12
    # Original example footer has a hard-coded 2/2; do not copy false pagination.
    for fp in sec.footer.paragraphs:
        if re.fullmatch(r"\\s*\\d+\\s*/\\s*\\d+\\s*",fp.text):
            fp.text=""
    return d

def add(d,text="",bold=False,italic=False,size=10,align=None,keep=False,space=6):
    p=d.add_paragraph()
    p.paragraph_format.space_after=Pt(space)
    if keep:
        p.paragraph_format.keep_with_next=True
    if align is not None:
        p.alignment=align
    r=p.add_run(str(text))
    r.bold=bold
    r.italic=italic
    r.font.name="Verdana"
    r.font.size=Pt(size)
    return p

def mix(d,blocks,space=6):
    p=d.add_paragraph()
    p.paragraph_format.space_after=Pt(space)
    for text,bold,italic in blocks:
        r=p.add_run(text)
        r.bold=bold
        r.italic=italic
        r.font.name="Verdana"
        r.font.size=Pt(10)
    return p

